uint8_t hid_input_len(uint8_t id)
{
	switch (id) {
	case RPT_MOUSE:    return 5;
	case RPT_KEYBOARD: return 8;
	case RPT_STATE:    return 53;
	case RPT_43:       return 14;
	case RPT_44:       return 5;
	case RPT_COMBINED: return 45;
	case RPT_STATUS:   return 1;
	case RPT_QUALITY:  return 12;
	default:           return 0;
	}
}

const uint8_t *hid_desc_slot(size_t *len) { *len = sizeof(slot_desc); return slot_desc; }
const uint8_t *hid_desc_dock(size_t *len) { *len = sizeof(dock_desc); return dock_desc; }
