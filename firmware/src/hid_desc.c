/* Vendor-page report: input/output/feature, ID, usage = ID, `n` bytes of 0..255. */
#define VENDOR_IN(id, n)   0x85, id, 0x09, id, 0x15, 0x00, 0x26, 0xFF, 0x00, 0x75, 0x08, 0x95, n, 0x81, 0x02
